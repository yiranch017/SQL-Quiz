"""Regenerate docs/answer_key.md (each question, its hint SQL and the live expected result).

Usage:  python scripts/answer_key.py      (reads DATABASE_URL like the other scripts)
"""
from pathlib import Path

from db import connect

OUT = Path(__file__).resolve().parent.parent / "docs" / "answer_key.md"


def md_table(cols, rows):
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    out += ["| " + " | ".join("NULL" if v is None else str(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    conn = connect()
    try:
        cur = conn.cursor()
        cur.execute("select id, position, topic, prompt, points, ordered, hint_sql "
                    "from public.quiz_questions order by position")
        parts = ["# Answer key\n",
                 "Generated by `python scripts/answer_key.py` from the live database. "
                 "Grading compares the *rows* a student's query returns with the rows below "
                 "(column names and numeric formatting are ignored; row order only matters for ordered questions).\n"]
        for qid, pos, topic, prompt, points, ordered, hint_sql in cur.fetchall():
            parts.append(f"## Q{pos} · {topic} · {points} points\n\n{prompt}\n")
            parts.append(f"Row order matters: **{'yes' if ordered else 'no'}**\n")
            parts.append(f"```sql\n{hint_sql}\n```\n")
            cur.execute(hint_sql.rstrip().rstrip(";"))
            cols = [d[0] for d in cur.description]
            parts.append(md_table(cols, cur.fetchall()) + "\n")
    finally:
        conn.close()
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
